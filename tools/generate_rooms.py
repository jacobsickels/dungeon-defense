# --- Room data. ----------------------------------------------------------------------
# Balance: blood per visitor per level (V) against build cost (C). Each tier is about 3× less
# efficient than the last (V ≈ C / (5 · 3^tier)), as in Cookie Clicker, where newer buildings
# cost more per unit of production. Without that, maxed lures make every tier pay for itself
# in seconds and the whole lineup unlocks in minutes.
def room(rid, name, desc, order, cost, extra, interior, layout=None):
    lines = ['[gd_resource type="Resource" script_class="RoomDef" format=3]', "",
             '[ext_resource type="Script" path="res://core/defs/room_def.gd" id="1_room"]',
             f'[ext_resource type="PackedScene" path="res://scenes/rooms/{interior}" id="2_interior"]']
    if layout:
        lines.append(f'[ext_resource type="Resource" path="res://data/layouts/{layout}.tres" id="3_layout"]')
    lines += ["", "[resource]", 'script = ExtResource("1_room")', f'id = &"{rid}"',
              f'display_name = "{name}"', f'description = "{desc}"', f"base_cost = {cost}",
              "buildable = true", "cost_growth = 1.15", f"line_order = {order}", "traverse_time = 3.0"]
    lines += extra
    if layout:
        lines.append('hazard_layout = ExtResource("3_layout")')
    lines.append('interior = ExtResource("2_interior")')
    write(f"data/rooms/{rid}.tres", "\n".join(lines) + "\n")


