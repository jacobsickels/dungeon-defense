"""Generates the room interiors, hazard layouts, piece scenes, and room data for the
D&D-style rooms. Run from the project root: python tools/generate_rooms.py

Rerun after changing a room here. Hand edits to the generated files are overwritten.
The Spike Corridor, Entrance, and Treasure Pit aren't generated by this script.
"""
import math
import os

D = "res://assets/third_party/kaykit/dungeon/"
F = "res://assets/third_party/kaykit/forest/"


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


# --- Piece scenes: a root Node3D with the piece script. ---------------------------------
def pieces():
    for name in ["skeleton_guard", "mimic_chest", "floating_sword", "glyph_rune"]:
        title = "".join(p.title() for p in name.split("_"))
        write(f"scenes/rooms/pieces/{name}.tscn", "\n".join([
            "[gd_scene format=3]", "",
            f'[ext_resource type="Script" path="res://scenes/rooms/pieces/{name}.gd" id="1"]', "",
            f'[node name="{title}" type="Node3D"]', 'script = ExtResource("1")', ""]))


# --- Hazard layouts. -----------------------------------------------------------------
LAYOUTS = {
    # name: spacing, extent, path_bias, jitter, keep_path_clear
    "crypt": (2.0, (2, 2), 2.5, 0.1, True),
    "mimic": (2.2, (2, 2), 2.5, 0.08, True),
    "armory": (1.6, (3, 2), 2.5, 0.12, True),
    "glyph": (1.5, (3, 3), 2.5, 0.1, False),
}


def layouts():
    for name, (sp, ext, bias, jit, clear) in LAYOUTS.items():
        write(f"data/layouts/{name}.tres", "\n".join([
            '[gd_resource type="Resource" script_class="HazardLayout" format=3]', "",
            '[ext_resource type="Script" path="res://core/hazard_layout.gd" id="1"]', "",
            "[resource]", 'script = ExtResource("1")',
            f"spacing = {sp}", f"extent = Vector2i({ext[0]}, {ext[1]})", f"path_bias = {bias}",
            f"jitter = {jit}", f"keep_path_clear = {'true' if clear else 'false'}", ""]))


# --- Interior scenes. ----------------------------------------------------------------
class Scene:
    def __init__(self, name):
        self.name = name
        self.ext = []
        self.nodes = []
        self.add_ext("Script", "res://scenes/rooms/room_interior.gd", "interior")

    def add_ext(self, typ, path, rid):
        if not any(e[2] == rid for e in self.ext):
            self.ext.append((typ, path, rid))
        return rid

    def scene(self, path):
        return self.add_ext("PackedScene", path, os.path.basename(path).split(".")[0])

    def node(self, text):
        self.nodes.append(text)

    def floor(self, tile="floor_tile_large", corner=None):
        self.node('[node name="Floor" type="Node3D" parent="."]')
        n = 0
        for x in (-4, 0, 4):
            for z in (-4, 0, 4):
                n += 1
                t = corner if (corner and x != 0 and z != 0) else tile
                rid = self.scene(D + t + ".gltf")
                self.node(f'[node name="Floor{n}" parent="Floor" instance=ExtResource("{rid}")]\n'
                          f"position = Vector3({x}, 0, {z})")

    def props(self):
        self.node('[node name="Props" type="Node3D" parent="."]')

    def text(self):
        out = ["[gd_scene format=3]", ""]
        for typ, path, rid in self.ext:
            out.append(f'[ext_resource type="{typ}" path="{path}" id="{rid}"]')
        out += ["", f'[node name="{self.name}" type="Node3D"]', 'script = ExtResource("interior")']
        for n in self.nodes:
            out += ["", n]
        return "\n".join(out) + "\n"


def spawner(s, piece, face_path=True, height=0.0):
    s.add_ext("Script", "res://scenes/rooms/level_spawner.gd", "spawner")
    rid = s.add_ext("PackedScene", f"res://scenes/rooms/pieces/{piece}.tscn", piece)
    s.node(f'[node name="Hazards" type="Node3D" parent="."]\nscript = ExtResource("spawner")\n'
           f'piece = ExtResource("{rid}")\nface_path = {"true" if face_path else "false"}\nheight = {height}')


def script_node(s, name, script, pos=(0, 0, 0), extra=""):
    rid = s.add_ext("Script", script, name.lower())
    s.node(f'[node name="{name}" type="Node3D" parent="."]\nposition = Vector3({pos[0]}, {pos[1]}, {pos[2]})\n'
           f'script = ExtResource("{rid}")' + extra)


def prop(s, name, model, pos, rot_y=0.0, scale=1.0, min_level=None, parent="Props"):
    rid = s.scene(model)
    t = (f'[node name="{name}" parent="{parent}" instance=ExtResource("{rid}")]\n'
         f"position = Vector3({pos[0]}, {pos[1]}, {pos[2]})")
    if rot_y:
        t += f"\nrotation = Vector3(0, {round(rot_y, 3)}, 0)"
    if scale != 1.0:
        t += f"\nscale = Vector3({scale}, {scale}, {scale})"
    if min_level is not None:
        t += f"\nmetadata/min_level = {min_level}"
    s.node(t)


def shrine(name, file, side_z, color, offerings):
    """A pedestal with a floating gem off to one side of the path, and a half ring of offerings
    (one more per level) in front of it, on the path side, so the camera sees them. They fill
    from the front middle outward, alternating left and right."""
    s = Scene(name)
    s.floor("floor_tile_large")
    s.props()
    prop(s, "Pedestal", D + "floor_foundation_allsides.gltf", (0, 0, side_z), scale=0.9)
    rid = s.add_ext("Script", "res://scenes/rooms/pieces/floating_gem.gd", "gem")
    s.node(f'[node name="Gem" type="Node3D" parent="."]\nposition = Vector3(0, 2.9, {side_z})\n'
           f'script = ExtResource("{rid}")\ncolor = Color({color})')
    toward = 1.0 if side_z < 0 else -1.0  # direction toward the path
    count = 14
    angles = [math.pi * (0.12 + 0.76 * k / (count - 1)) for k in range(count)]
    # Middle first, then alternating outward: indices 6, 7, 5, 8, 4, ...
    middle = (count - 1) / 2.0
    order = sorted(range(count), key=lambda k: (abs(k - middle), k))
    for level, k in enumerate(order, start=1):
        a = angles[k]
        x = round(math.cos(a) * 2.4, 2)
        z = round(side_z + toward * math.sin(a) * 1.9, 2)
        prop(s, f"Offering{level}", D + offerings[level % len(offerings)] + ".gltf", (x, 0, z),
             rot_y=level * 0.7, min_level=level)
    write("scenes/rooms/" + file, s.text())


